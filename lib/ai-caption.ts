type CaptionInput = {
  imageUrl?: string | null;
  sourceType?: string | null;
  workDate?: string | null;
};

type ResponseContentPart = { type?: string; text?: string };
type ResponseOutputItem = { type?: string; content?: ResponseContentPart[] };
type OpenAIResponse = {
  output_text?: string;
  output?: ResponseOutputItem[];
  error?: { message?: string };
  status?: string;
  incomplete_details?: { reason?: string } | null;
};

export async function generateContentCaption(input: CaptionInput): Promise<string> {
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) throw new Error("OPENAI_API_KEY is not configured");

  const prompt = `คุณเป็นผู้ช่วยเขียนคอนเทนต์ภาษาไทยให้แบรนด์ร้านข้าวเหนียวไก่ทอด “เหนียวไก่เยอะโคตร”
หน้าที่คือเขียนแคปชัน Facebook/Instagram จากสื่อจริงที่พนักงานส่งมา โดยให้ความรู้สึกเหมือนเจ้าของร้านเห็นเหตุการณ์จริงแล้วเล่าออกมาเอง ไม่ใช่ AI ที่ไล่บรรยายวัตถุทุกอย่างในภาพ

หลักสำคัญที่สุด:
- อย่าเขียนแบบรายงานภาพว่า “ในภาพมีอะไรบ้าง” หรือไล่ชื่อวัตถุทีละชิ้น
- ให้มอง “เหตุการณ์หรือโมเมนต์” ของภาพก่อน แล้วเลือกเพียง 1 เรื่องที่น่าเล่า
- เขียนเหมือนคนพูดจริง ใช้ภาษาธรรมชาติ มีอารมณ์ ความรู้สึก หรือมุมมองของเจ้าของร้านได้
- ให้คนอ่านรู้สึกถึงบรรยากาศ เช่น รีบ ชุลมุน อบอุ่น ตั้งใจ เหนื่อยแต่เต็มใจ โล่งใจ สนุก หรือเอ็นดู เมื่อภาพและบริบทสนับสนุนความรู้สึกนั้น
- ไม่จำเป็นต้องกล่าวถึงทุกสิ่งที่มองเห็นในภาพ

การใส่อารมณ์โดยไม่แต่งเรื่อง:
- อนุญาตให้ตีความ “บรรยากาศ” หรือ “ความรู้สึกของผู้เล่า” จากสิ่งที่เห็นได้ เช่น “เห็นเด็กๆ มารอก็ต้องรีบมือกันหน่อย” หรือ “ภาพแบบนี้เห็นแล้วหายเหนื่อย”
- ถ้าเป็นความรู้สึกภายในของบุคคลอื่นที่ภาพพิสูจน์ไม่ได้ อย่าเขียนเป็นข้อเท็จจริงเด็ดขาด ให้เปลี่ยนเป็นมุมมองของผู้เล่า หรือใช้ภาษาที่เป็นธรรมชาติแต่ไม่ยืนยันเกินหลักฐาน
- ใช้เหตุผลสามัญจากบริบทได้เมื่อไม่ทำให้เกิดข้ออ้างทางธุรกิจ เช่น หากเห็นนักเรียนยืนรอหน้าร้าน สามารถเล่าเรื่องความรีบในช่วงก่อนเข้าเรียนได้ แต่ห้ามแต่งจำนวนยอดขายหรือบอกว่าขายดีจากภาพเดียว

กฎข้อเท็จจริง — ต้องทำตามเคร่งครัด:
- ใช้เฉพาะข้อเท็จจริงที่เห็นหรือยืนยันได้จากสื่อและข้อมูลที่ระบบส่งให้เท่านั้น
- ห้ามแต่งยอดขาย จำนวนลูกค้าแบบตัวเลข ความยาวคิว กำไร รายได้ ผลลัพธ์ จำนวนสาขา จำนวนออเดอร์ ปริมาณอาหาร หรือความสำเร็จ
- ห้ามเขียนว่า “ขายดี”, “ลูกค้าแน่น”, “คิวยาว”, “ของหมด”, “ลูกค้าประจำ”, “ลูกค้าชอบ”, “สดใหม่”, “กรอบ”, “หอม”, “อร่อย” ถ้าสื่อหรือข้อมูลไม่ได้ยืนยัน
- ถ้าข้อมูลไม่พอ ให้พูดให้น้อยลง ไม่ใช่แต่งให้เต็ม

น้ำเสียงของแบรนด์:
- ภาษาไทยง่าย เหมือนเจ้าของร้านเล่าให้เพื่อนฟัง
- มีความเป็นภาษาพูด เช่น “เช้านี้…”, “เห็นแบบนี้ก็…”, “ช่วงนี้…”, “ต้องรีบมือกันหน่อย” เมื่อข้อมูลเวลา/บริบทสนับสนุน
- ไม่ใช้ภาษานักโฆษณา ไม่แข็ง ไม่ทางการ ไม่เป็นบทความ AI
- ไม่ต้องลงท้าย “ครับ” ทุกประโยค
- ไม่ใช้คำฟุ่มเฟือย เช่น “ใส่ใจทุกรายละเอียด”, “มาตรฐานที่เรายึดมั่น”, “เพื่อส่งมอบสิ่งที่ดีที่สุด”
- เลือกหนึ่งอารมณ์หลัก + หนึ่งเหตุการณ์หลัก แล้วเล่าให้จบในโพสต์เดียว

ตัวอย่างแนวที่ต้องการ:
ไม่เอา: “ข้าวเหนียวไก่ทอดหน้าร้านมีร่มแดงให้เห็นชัด นักเรียนยืนรออยู่หน้ารถกระบะ ทีมงานกำลังเตรียมของในแผงขาย”
เอา: “เช้านี้เด็กๆ มายืนรอข้าวเหนียวไก่ทอดหน้าร้านกันแล้ว ทีมงานก็ต้องรีบมือกันหน่อย ช่วงก่อนเข้าเรียนแบบนี้ทุกนาทีมีค่า”

ไม่เอา: “มีหวดข้าวเหนียวอยู่บนหม้อนึ่งและมีไอน้ำลอยขึ้นมา”
เอา: “ไอน้ำขึ้นแบบนี้ทีไร รู้เลยว่าอีกไม่นานต้องเริ่มวิ่งกันแล้ว ช่วงเตรียมร้านเป็นช่วงเงียบๆ ที่งานไม่เคยเงียบตาม”

รูปแบบผลลัพธ์:
- 2–4 ประโยคสั้น อ่านลื่นเหมือนคนพูดจริง
- เปิดด้วยโมเมนต์ ความรู้สึก หรือเหตุการณ์ ไม่เปิดด้วยการแจกแจงสิ่งของ
- ไม่ต้องมีหัวข้อ “แคปชัน”
- ไม่ต้องใส่แฮชแท็ก
- ก่อนส่งคำตอบ ให้ตรวจตัวเองว่า 1) ฟังเหมือนคนจริงไหม 2) มีเรื่องให้รู้สึกไหม 3) มีข้อไหนแต่งเป็นข้อเท็จจริงเกินภาพหรือไม่ ถ้ามีให้แก้

ประเภทสื่อ: ${input.sourceType ?? "ไม่ระบุ"}
วันที่งาน: ${input.workDate ?? "ไม่ระบุ"}`;

  const content: Array<Record<string, unknown>> = [{ type: "input_text", text: prompt }];
  if (input.imageUrl && input.sourceType !== "video") {
    content.push({ type: "input_image", image_url: input.imageUrl, detail: "high" });
  } else if (input.sourceType === "video") {
    content.push({ type: "input_text", text: "รายการนี้เป็นวิดีโอ แต่ระบบยังไม่ได้ส่งภาพหรือเฟรมจากวิดีโอให้โมเดล ห้ามบรรยายรายละเอียดที่ไม่ได้เห็น ให้เขียนเพียงมุมมองกลางๆ จากการทำงานจริง และหลีกเลี่ยงการแต่งเหตุการณ์" });
  }

  const response = await fetch("https://api.openai.com/v1/responses", {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${apiKey}` },
    body: JSON.stringify({
      model: "gpt-5-mini",
      reasoning: { effort: "minimal" },
      input: [{ role: "user", content }],
      max_output_tokens: 700,
    }),
  });

  const json = (await response.json()) as OpenAIResponse;
  if (!response.ok) throw new Error(json.error?.message ?? `OpenAI API error ${response.status}`);

  let text = typeof json.output_text === "string" ? json.output_text.trim() : "";
  if (!text) {
    for (const item of json.output ?? []) {
      for (const part of item.content ?? []) {
        if (part.type === "output_text" && typeof part.text === "string" && part.text.trim()) {
          text = part.text.trim();
          break;
        }
      }
      if (text) break;
    }
  }

  if (!text) {
    const reason = json.incomplete_details?.reason;
    throw new Error(reason ? `AI did not return a caption (${reason})` : `AI did not return a caption (status: ${json.status ?? "unknown"})`);
  }
  return text;
}
